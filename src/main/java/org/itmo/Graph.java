package org.itmo;

import lombok.SneakyThrows;

import java.util.ArrayList;
import java.util.LinkedList;
import java.util.Objects;
import java.util.Queue;
import java.util.concurrent.Callable;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicIntegerArray;
import java.util.stream.IntStream;

class Graph {
    private final int V;
    private final ArrayList<Integer>[] adjList;
    private final int maxThreads = Runtime.getRuntime().availableProcessors();

    Graph(int vertices) {
        this.V = vertices;
        adjList = new ArrayList[vertices];
        for (int i = 0; i < vertices; ++i) {
            adjList[i] = new ArrayList<>();
        }
    }

    void addEdge(int src, int dest) {
        if (!adjList[src].contains(dest)) {
            adjList[src].add(dest);
        }
    }

    // Паралелльный обход
    @SneakyThrows
    long parallelBFS(int startVertex) {
        var visited = new AtomicIntegerArray(V);
        visited.set(startVertex, 1);

        Queue<Integer> frontier = new ConcurrentLinkedQueue<>();
        frontier.add(startVertex);

        var executor = Executors.newFixedThreadPool(maxThreads);
        try {
            while (!frontier.isEmpty()) {
                Queue<Integer> nextFrontier = new ConcurrentLinkedQueue<>();

                var currentLevel = new ArrayList<>(frontier);
                if (currentLevel.isEmpty()) {
                    break;
                }

                int threads = Math.min(maxThreads, currentLevel.size());
                int chunkSize = (currentLevel.size() + threads - 1) / threads;

                var tasks = IntStream.range(0, threads)
                        .mapToObj(task -> {
                            int from = task * chunkSize;
                            int to = Math.min(currentLevel.size(), from + chunkSize);
                            if (from >= to) {
                                return null;
                            }

                            return (Callable<Void>) () -> {
                                currentLevel.subList(from, to).stream()
                                        .flatMap(currentVertex -> adjList[currentVertex].stream())
                                        .filter(neighbor -> visited.compareAndSet(neighbor, 0, 1))
                                        .forEach(nextFrontier::add);
                                return null;
                            };
                        })
                        .filter(Objects::nonNull)
                        .toList();

                executor.invokeAll(tasks);
                frontier = nextFrontier;
            }
        } finally {
            executor.shutdown();
        }

        return IntStream.range(0, visited.length())
                .filter(i -> visited.get(i) == 1)
                .count();
    }

    //Generated by ChatGPT
    void bfs(int startVertex) {
        boolean[] visited = new boolean[V];

        LinkedList<Integer> queue = new LinkedList<>();

        visited[startVertex] = true;
        queue.add(startVertex);

        while (!queue.isEmpty()) {
            startVertex = queue.poll();

            for (int n : adjList[startVertex]) {
                if (!visited[n]) {
                    visited[n] = true;
                    queue.add(n);
                }
            }
        }
    }

}
